type MessagePair = readonly [chinese: string, english: string]
type MessageSource = { readonly [key: string]: MessagePair | MessageSource }
type LocalizedMessages<T> = T extends MessagePair
  ? string
  : { readonly [K in keyof T]: LocalizedMessages<T[K]> }

const localize = <T extends MessageSource>(source: T, localeIndex: 0 | 1): LocalizedMessages<T> =>
  Object.fromEntries(
    Object.entries(source).map(([key, value]) => [
      key,
      Array.isArray(value)
        ? value[localeIndex]
        : localize(value as MessageSource, localeIndex)
    ])
  ) as LocalizedMessages<T>

